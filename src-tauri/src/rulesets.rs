//! On-disk cache for rule-set lists.
//!
//! The JSON document (see [`crate::store`]) keeps only rule-set metadata; the
//! list itself is a separate file per set, named after the set id. That keeps
//! the document small enough to rewrite on every edit — a provider can be tens
//! of thousands of lines, and a routing change should not rewrite all of them.
//!
//! The text is stored verbatim as fetched: if a future version learns to parse
//! a new line type, existing caches keep working without a re-download.

use std::path::PathBuf;

use crate::domain::ruleset::{parse_entries, ParsedSet, RuleSet};
use crate::error::{AppError, AppResult};

pub struct RuleSetCache {
    dir: PathBuf,
}

impl RuleSetCache {
    pub fn new(dir: impl Into<PathBuf>) -> Self {
        Self { dir: dir.into() }
    }

    /// Where this set's list lives. Ids are generated by us (`rs-<suffix>`), so
    /// there is no path-traversal risk, but the name is still derived through
    /// the set id rather than the user-visible name.
    pub fn path_for(&self, set: &RuleSet) -> PathBuf {
        self.dir.join(format!("{}.list", set.id))
    }

    /// Cached text, or an empty string when the set was never fetched.
    pub fn read(&self, set: &RuleSet) -> AppResult<String> {
        match std::fs::read_to_string(self.path_for(set)) {
            Ok(text) => Ok(text),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(String::new()),
            Err(error) => Err(AppError::Io(error.to_string())),
        }
    }

    pub fn write(&self, set: &RuleSet, text: &str) -> AppResult<()> {
        std::fs::create_dir_all(&self.dir)?;
        std::fs::write(self.path_for(set), text)?;
        Ok(())
    }

    pub fn remove(&self, set: &RuleSet) -> AppResult<()> {
        match std::fs::remove_file(self.path_for(set)) {
            Ok(()) => Ok(()),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(error) => Err(AppError::Io(error.to_string())),
        }
    }

    /// Parse the cached list. A missing cache is an empty set, not an error:
    /// a set the user just created has nothing to parse yet.
    pub fn entries(&self, set: &RuleSet) -> AppResult<ParsedSet> {
        let text = self.read(set)?;
        Ok(parse_entries(&text))
    }
}

#[cfg(test)]
mod tests {
    use std::sync::atomic::{AtomicUsize, Ordering};

    use super::*;

    fn scratch() -> PathBuf {
        static SEQ: AtomicUsize = AtomicUsize::new(0);
        let seq = SEQ.fetch_add(1, Ordering::Relaxed);
        let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("target")
            .join("test-tmp")
            .join(format!("rulesets-{}-{}", std::process::id(), seq));
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn set() -> RuleSet {
        RuleSet::new("广告".into(), String::new())
    }

    #[test]
    fn a_set_that_was_never_written_reads_as_empty() {
        let dir = scratch();
        let cache = RuleSetCache::new(dir.join("rulesets"));
        let parsed = cache.entries(&set()).unwrap();
        assert!(parsed.entries.is_empty());
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn writing_and_reading_round_trips_the_entries() {
        let dir = scratch();
        let cache = RuleSetCache::new(dir.join("rulesets"));
        let set = set();
        cache
            .write(&set, "payload:\n  - '+.ads.example'\n  - 10.0.0.0/8\n")
            .unwrap();
        let parsed = cache.entries(&set).unwrap();
        assert_eq!(parsed.entries.len(), 2);
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn removing_a_set_that_is_not_there_is_not_an_error() {
        let dir = scratch();
        let cache = RuleSetCache::new(dir.join("rulesets"));
        assert!(cache.remove(&set()).is_ok());
        std::fs::remove_dir_all(&dir).ok();
    }

    #[test]
    fn each_set_gets_its_own_file() {
        let dir = scratch();
        let cache = RuleSetCache::new(dir.join("rulesets"));
        let first = set();
        let second = set();
        assert_ne!(cache.path_for(&first), cache.path_for(&second));
        std::fs::remove_dir_all(&dir).ok();
    }
}
