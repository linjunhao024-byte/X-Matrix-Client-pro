"""Generate src/i18n/{zh,en,tw}.ts from scripts/i18n-pairs.json.

All three files come from one table so the dictionaries can never drift apart:
adding a key means adding a row with every translation, or the generator fails.
The Traditional column (`zh-tw`, Taiwan wording) is the fourth cell. It was
produced once by zhconv plus a small phrase table (see docs/HANDOVER.md 42) and
lives in the pair table, so regenerating the dictionaries needs no Python extra.
"""
import io, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAIRS = os.path.join(ROOT, "scripts", "i18n-pairs.json")
OUT = os.path.join(ROOT, "src", "i18n")


def main() -> int:
    pairs = json.load(io.open(PAIRS, encoding="utf-8"))
    seen = set()
    order = []
    rows = []
    for row in pairs:
        if len(row) != 4:
            print("row %r has %d cells, expected 4 (key, zh, en, tw)" % (row[0], len(row)), file=sys.stderr)
            return 1
        key, zh, en, tw = row
        if key in seen:
            print("duplicate key: " + key, file=sys.stderr)
            return 1
        seen.add(key)
        group = key.split(".")[0]
        if group not in order:
            order.append(group)
        rows.append((group, key, zh, en, tw))

    for lang, index in (("zh", 2), ("en", 3), ("tw", 4)):
        lines = [
            "// Generated by scripts/gen_i18n.py from scripts/i18n-pairs.json.",
            "// Do not edit by hand: add a row to the pair table and regenerate.",
            "export const " + lang + ": Record<string, string> = {",
        ]
        for group in order:
            lines.append("  // " + group)
            for g, key, zh, en, tw in rows:
                if g != group:
                    continue
                value = (zh, en, tw)[index - 2]
                lines.append("  " + json.dumps(key, ensure_ascii=False) + ": " + json.dumps(value, ensure_ascii=False) + ",")
        lines.append("}")
        path = os.path.join(OUT, lang + ".ts")
        io.open(path, "w", encoding="utf-8", newline=chr(10)).write(chr(10).join(lines) + chr(10))
        print("wrote " + path + " (%d keys)" % len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
