"""Generate src/i18n/{zh,en}.ts from scripts/i18n-pairs.json.

Both files come from one table so the two dictionaries can never drift apart:
adding a key means adding a row with BOTH translations, or the generator fails.
"""
import io, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAIRS = os.path.join(ROOT, "scripts", "i18n-pairs.json")
OUT = os.path.join(ROOT, "src", "i18n")


def main() -> int:
    pairs = json.load(io.open(PAIRS, encoding="utf-8"))
    seen = set()
    order = []
    rows = []
    for key, zh, en in pairs:
        if key in seen:
            print("duplicate key: " + key, file=sys.stderr)
            return 1
        seen.add(key)
        group = key.split(".")[0]
        if group not in order:
            order.append(group)
        rows.append((group, key, zh, en))

    for lang, index in (("zh", 2), ("en", 3)):
        lines = [
            "// Generated by scripts/gen_i18n.py from scripts/i18n-pairs.json.",
            "// Do not edit by hand: add a row to the pair table and regenerate.",
            "export const " + lang + ": Record<string, string> = {",
        ]
        for group in order:
            lines.append("  // " + group)
            for g, key, zh, en in rows:
                if g != group:
                    continue
                value = (zh, en)[index - 2]
                lines.append("  " + json.dumps(key, ensure_ascii=False) + ": " + json.dumps(value, ensure_ascii=False) + ",")
        lines.append("}")
        path = os.path.join(OUT, lang + ".ts")
        io.open(path, "w", encoding="utf-8", newline=chr(10)).write(chr(10).join(lines) + chr(10))
        print("wrote " + path + " (%d keys)" % len(rows))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
